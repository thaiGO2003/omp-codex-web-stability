#!/usr/bin/env python3
"""Refresh the standalone PowerShell installer's embedded patch and TS module."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
script = root / 'bin/apply-sse-watchdog.ps1'
begin = '# BEGIN EMBEDDED WATCHDOG'
end = '# END EMBEDDED WATCHDOG'
text = script.read_text()
if text.count(begin) != 1 or text.count(end) != 1:
    raise SystemExit('Expected one pair of embedded payload markers')
manifest = (root / 'fixes/sse-integration.json').read_text().rstrip('\n')
module = (root / 'fixes/sse-watchdog.ts').read_text().rstrip('\n')
if any(line == "'@" for payload in [manifest, module] for line in payload.splitlines()):
    raise SystemExit('Payload would terminate a PowerShell here-string')
payload = (begin + '\n# Generated by bin/build-powershell.py; no companion files required.\n'
           + "$manifestJson = @'\n" + manifest + "\n'@\n"
           + "$moduleText = @'\n" + module + "\n'@\n" + '$moduleText += "`n"\n' + end)
start = text.index(begin)
stop = text.index(end, start) + len(end)
script.write_text(text[:start] + payload + text[stop:])

begin_config = '# BEGIN EMBEDDED CONFIG'
end_config = '# END EMBEDDED CONFIG'
text = script.read_text()
module = (root / 'fixes/omp-config.ts').read_text().rstrip('\n')
if text.count(begin_config) != 1 or text.count(end_config) != 1 or "'@" in module.splitlines():
    raise SystemExit('Invalid config payload markers or delimiter')
start = text.index(begin_config)
stop = text.index(end_config, start) + len(end_config)
payload = begin_config + "\n$configModuleText = @'\n" + module + "\n'@\n" + end_config
script.write_text(text[:start] + payload + text[stop:])
