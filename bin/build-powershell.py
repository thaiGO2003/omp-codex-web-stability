#!/usr/bin/env python3
"""Refresh the standalone PowerShell installer's embedded patch and TS module."""
from pathlib import Path
import json

root = Path(__file__).resolve().parent.parent
script = root / 'bin/apply-sse-watchdog.ps1'
begin = '# BEGIN EMBEDDED WATCHDOG'
end = '# END EMBEDDED WATCHDOG'
text = script.read_text()
if text.count(begin) != 1 or text.count(end) != 1:
    raise SystemExit('Expected one pair of embedded payload markers')
manifest = (root / 'fixes/sse-integration.json').read_text().rstrip('\n')
module = (root / 'fixes/sse-watchdog.ts').read_text().rstrip('\n')
if any(line == "'@" for payload in [manifest, module] for line in payload.splitlines()):
    raise SystemExit('Payload would terminate a PowerShell here-string')
payload = (begin + '\n# Generated by bin/build-powershell.py; no companion files required.\n'
           + "$manifestJson = @'\n" + manifest + "\n'@\n"
           + "$moduleText = @'\n" + module + "\n'@\n" + '$moduleText += "`n"\n' + end)
start = text.index(begin)
stop = text.index(end, start) + len(end)
script.write_text(text[:start] + payload + text[stop:])

begin_config = '# BEGIN EMBEDDED CONFIG'
end_config = '# END EMBEDDED CONFIG'
text = script.read_text()
module = (root / 'fixes/omp-config.ts').read_text().rstrip('\n')
if text.count(begin_config) != 1 or text.count(end_config) != 1 or "'@" in module.splitlines():
    raise SystemExit('Invalid config payload markers or delimiter')
start = text.index(begin_config)
stop = text.index(end_config, start) + len(end_config)
payload = begin_config + "\n$configModuleText = @'\n" + module + "\n'@\n" + end_config
script.write_text(text[:start] + payload + text[stop:])

# The Web setup is self-contained, including the base shim and OMP request hook.
files = {name: (root / 'shim' / name).read_text() for name in
         ['server.ts', 'compatibility.ts', 'task-label.ts', 'tool-call-ids.ts', 'start-shim.ps1']}
files['sse-watchdog.ts'] = (root / 'fixes/sse-watchdog.ts').read_text()
(root / 'shim/sse-watchdog.ts').write_text(files['sse-watchdog.ts'])
web_payload = json.dumps({
    'configModule': (root / 'fixes/omp-web-config.ts').read_text(),
    'extension': (root / 'shim/omp-extension.ts').read_text(),
    'files': files,
}, ensure_ascii=True, indent=2)
template = (root / 'bin/setup-omp-codex-web.template.ps1').read_text()
marker = '# EMBEDDED WEB SETUP PAYLOAD'
if template.count(marker) != 1:
    raise SystemExit('Expected one Web setup payload marker')
embedded = "# Generated by bin/build-powershell.py; no companion files required.\n$payloadJson = @'\n" + web_payload + "\n'@"
(root / 'bin/setup-omp-codex-web.ps1').write_text(template.replace(marker, embedded))

# The root installer can be downloaded alone; BAT is just an optional launcher.
windows_payload = json.dumps({'scripts': {
    name: (root / 'bin' / name).read_text() for name in [
        'setup-omp-codex-web.ps1', 'apply-sse-watchdog.ps1',
        'apply-send-timeout.ps1', 'apply-browser-rebinding.ps1',
    ]
}}, ensure_ascii=True, indent=2)
template = (root / 'bin/install-windows.template.ps1').read_text()
marker = '# EMBEDDED WINDOWS INSTALL PAYLOAD'
if template.count(marker) != 1:
    raise SystemExit('Expected one Windows install payload marker')
embedded = ("# Generated by bin/build-powershell.py; no companion files required.\n"
            + "$payloadJson = @'\n" + windows_payload + "\n'@")
(root / 'install.ps1').write_text(template.replace(marker, embedded))
