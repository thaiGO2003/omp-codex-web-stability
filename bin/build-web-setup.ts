#!/usr/bin/env bun
// Regenerate the standalone Windows Web installer without requiring Python.
// bin/build-powershell.py remains the full cross-platform bundle generator.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const read = (name: string) => readFileSync(resolve(root, name), "utf8");
const asciiJson = (value: unknown) => JSON.stringify(value, null, 2).replace(/[\u007f-\uffff]/g,
  char => `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`);
const embed = (template: string, marker: string, data: unknown, comment: string) => {
  if (template.split(marker).length !== 2) throw Error(`Expected exactly one ${marker} marker`);
  const json = asciiJson(data);
  if (json.split("\n").some(line => line === "'@")) throw Error("Unsafe PowerShell here-string terminator");
  const replacement = `${comment}\n$payloadJson = @'\n${json}\n'@`;
  // String.replace treats $', $& and $` in a replacement string as special
  // substitutions. Bundled PowerShell legitimately contains those sequences,
  // so insert through a callback to preserve the payload byte-for-byte.
  return template.replace(marker, () => replacement);
};

const validateEmbeddedPayload = (script: string, name: string) => {
  const startMarker = "$payloadJson = @'\n";
  const start = script.indexOf(startMarker);
  const end = start < 0 ? -1 : script.indexOf("\n'@", start + startMarker.length);
  if (start < 0 || end < 0) throw Error(`${name} has no complete embedded payload`);
  JSON.parse(script.slice(start + startMarker.length, end).replace(/\r$/, ""));
};
const files: Record<string, string> = {};
for (const name of ["server.ts", "compatibility.ts", "task-label.ts", "tool-call-ids.ts",
  "diagnostics.ts", "submitted-turn-retry.ts", "start-shim.ps1"]) {
  files[name] = read(`shim/${name}`);
}
files["sse-watchdog.ts"] = read("fixes/sse-watchdog.ts");

const webSetup = embed(read("bin/setup-omp-codex-web.template.ps1"), "# EMBEDDED WEB SETUP PAYLOAD", {
  configModule: read("fixes/omp-web-config.ts"),
  extension: read("shim/omp-extension.ts"),
  files,
}, "# Generated by bin/build-powershell.py; no companion files required.");

const scriptNames = ["setup-omp-codex-web.ps1", "apply-sse-watchdog.ps1",
  "apply-send-timeout.ps1", "apply-browser-rebinding.ps1", "apply-browser-rebinding-617.ps1",
  "watch-codex-web.ps1"];
const bundled = Object.fromEntries(scriptNames.map(name =>
  [name, name === "setup-omp-codex-web.ps1" ? webSetup : read(`bin/${name}`)]));
const installer = embed(read("bin/install-windows.template.ps1"), "# EMBEDDED WINDOWS INSTALL PAYLOAD",
  { scripts: bundled }, "# Generated by bin/build-powershell.py; no companion files required.");
validateEmbeddedPayload(webSetup, "bin/setup-omp-codex-web.ps1");
validateEmbeddedPayload(installer, "install.ps1");

const outputs = [["bin/setup-omp-codex-web.ps1", webSetup], ["install.ps1", installer]] as const;
const check = process.argv.includes("--check");
for (const [name, data] of outputs) {
  if (check) {
    if (read(name).replace(/\r\n/g, "\n") !== data.replace(/\r\n/g, "\n"))
      throw Error(`${name} must be regenerated with bun bin/build-web-setup.ts`);
  } else writeFileSync(resolve(root, name), data);
}
console.log(check ? "Windows Web bundles are up-to-date" : "Regenerated Windows Web setup and root installer");
